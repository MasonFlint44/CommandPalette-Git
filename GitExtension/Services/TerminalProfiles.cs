namespace GitExtension.Services;

/// <summary>Where a Windows Terminal profile comes from.</summary>
internal enum TerminalProfileKind
{
    /// <summary>Written by the user, or added by a fragment that isn't a Store app.</summary>
    Other,

    /// <summary>Generated by Windows Terminal for a WSL distro.</summary>
    GeneratedWsl,

    /// <summary>Installed by a Store app, such as a WSL distro app's profile.</summary>
    StoreApp,
}

/// <summary>
/// A Windows Terminal profile. <see cref="Id"/> is its GUID ("{...}"); <see cref="Label"/> is
/// its name, with a suffix when several profiles share that name. <see cref="HasCommandLine"/>
/// is whether settings.json sets its command line, i.e. the user wrote or overrode it.
/// </summary>
internal sealed record TerminalProfile(string Id, string Name, string Label, bool Hidden, TerminalProfileKind Kind, bool HasCommandLine)
{
    /// <summary>
    /// Whether, for a WSL repository, the profile only launches a distro: one Terminal generated
    /// or a Store app installed (assumed to be a distro app's), with its command line left as
    /// shipped. Its command line is then replaced with wsl.exe (see OpenInTerminalCommand).
    /// </summary>
    public bool IsDistroLauncher => Kind != TerminalProfileKind.Other && !HasCommandLine;
}

/// <summary>
/// Reads profiles from Windows Terminal's settings and picks the one a repository opens with.
/// </summary>
internal static partial class TerminalProfiles
{
    private const string GeneratedWslSource = "Windows.Terminal.Wsl";

    // Windows Terminal's namespace for the GUIDs of profiles it generates
    private static readonly Guid TerminalProfileNamespace = new("2BDE4A90-D05F-401C-9492-E40884EAD1D8");

    private static string SettingsPath => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
        "Packages",
        "Microsoft.WindowsTerminal_8wekyb3d8bbwe",
        "LocalState",
        "settings.json");

    /// <summary>
    /// All profiles in Windows Terminal's settings, hidden ones included, in settings order.
    /// Empty if Terminal isn't installed or its settings can't be read.
    /// </summary>
    public static List<TerminalProfile> Load()
    {
        string json;
        try
        {
            json = File.ReadAllText(SettingsPath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return [];
        }

        var entries = new List<(string Id, string Name, bool Hidden, TerminalProfileKind Kind, bool HasCommandLine)>();
        try
        {
            using var document = JsonDocument.Parse(json, new JsonDocumentOptions
            {
                CommentHandling = JsonCommentHandling.Skip,
                AllowTrailingCommas = true,
            });

            // "profiles" is either { "list": [...] } or, in older settings files, the array itself
            var profiles = document.RootElement.TryGetProperty("profiles", out var element) ? element : default;
            if (profiles.ValueKind == JsonValueKind.Object)
            {
                profiles = profiles.TryGetProperty("list", out var list) ? list : default;
            }

            if (profiles.ValueKind != JsonValueKind.Array)
            {
                return [];
            }

            foreach (var profile in profiles.EnumerateArray())
            {
                var name = GetString(profile, "name")?.Trim();
                if (!string.IsNullOrEmpty(name) && Guid.TryParse(GetString(profile, "guid"), out var id))
                {
                    var hidden = profile.TryGetProperty("hidden", out var hiddenElement) && hiddenElement.ValueKind == JsonValueKind.True;
                    var source = GetString(profile, "source");
                    var kind = source == GeneratedWslSource ? TerminalProfileKind.GeneratedWsl
                        : source is not null && PackageFamilyNameRegex().IsMatch(source) ? TerminalProfileKind.StoreApp
                        : TerminalProfileKind.Other;
                    entries.Add((id.ToString("B"), name, hidden, kind, !string.IsNullOrWhiteSpace(GetString(profile, "commandline"))));
                }
            }
        }
        catch (JsonException)
        {
            return [];
        }

        // Profiles sharing a name are told apart: the one Terminal generated for a WSL distro
        // becomes "Name (WSL)"; if one other remains it keeps the plain name, otherwise the
        // others are numbered "Name (1)", "Name (2)", ... in settings order.
        var result = new List<TerminalProfile>();
        var numbered = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        foreach (var entry in entries)
        {
            var sameName = entries.Where(e => string.Equals(e.Name, entry.Name, StringComparison.OrdinalIgnoreCase)).ToList();
            var others = sameName.Count(e => e.Kind != TerminalProfileKind.GeneratedWsl);

            string label;
            if (sameName.Count == 1)
            {
                label = entry.Name;
            }
            else if (entry.Kind == TerminalProfileKind.GeneratedWsl)
            {
                label = $"{entry.Name} (WSL)";
            }
            else if (others == 1)
            {
                label = entry.Name;
            }
            else
            {
                numbered[entry.Name] = numbered.GetValueOrDefault(entry.Name) + 1;
                label = $"{entry.Name} ({numbered[entry.Name]})";
            }

            result.Add(new TerminalProfile(entry.Id, entry.Name, label, entry.Hidden, entry.Kind, entry.HasCommandLine));
        }

        return result;
    }

    /// <summary>
    /// The profile a repository opens with: its own choice, else <see cref="RepoDefault"/>.
    /// Null means Windows Terminal's default profile. Choices that no longer match a profile
    /// are skipped.
    /// </summary>
    public static TerminalProfile? Resolve(GitRepoInfo repo, GitRepoSettingsManager settings, List<TerminalProfile> profiles) =>
        ById(profiles, settings.GetRepoTerminalProfile(repo.ChoiceKey)) ?? RepoDefault(repo, settings, profiles);

    /// <summary>
    /// The profile a repository opens with when it has no choice of its own: for WSL, the
    /// distro's choice, else <see cref="DistroDefault"/>; otherwise the global setting.
    /// </summary>
    public static TerminalProfile? RepoDefault(GitRepoInfo repo, GitRepoSettingsManager settings, List<TerminalProfile> profiles) =>
        repo.IsWsl
            ? ById(profiles, settings.GetDistroTerminalProfile(repo.Distro!)) ?? DistroDefault(repo.Distro!, settings, profiles)
            : ById(profiles, settings.TerminalProfile);

    /// <summary>
    /// The profile a distro's repositories open with when the distro has no choice: the distro
    /// app's profile, else the profile Terminal generated for the distro, else the global setting.
    /// </summary>
    public static TerminalProfile? DistroDefault(string distro, GitRepoSettingsManager settings, List<TerminalProfile> profiles) =>
        DistroAppProfile(profiles, distro)
            ?? ById(profiles, GeneratedWslProfileId(distro))
            ?? ById(profiles, settings.TerminalProfile);

    public static TerminalProfile? ById(List<TerminalProfile> profiles, string? id) =>
        profiles.FirstOrDefault(p => string.Equals(p.Id, id, StringComparison.OrdinalIgnoreCase));

    /// <summary>
    /// The GUID Windows Terminal gives the profile it generates for a WSL distro: a version 5
    /// UUID of the distro name (UTF-16LE) in Terminal's profile namespace.
    /// </summary>
    public static string GeneratedWslProfileId(string distro)
    {
        var input = TerminalProfileNamespace.ToByteArray(bigEndian: true).Concat(Encoding.Unicode.GetBytes(distro)).ToArray();
#pragma warning disable CA5350 // SHA-1 is what the UUID v5 algorithm specifies; this isn't a security use
        var hash = SHA1.HashData(input);
#pragma warning restore CA5350
        var bytes = hash[..16];
        bytes[6] = (byte)((bytes[6] & 0x0F) | 0x50); // version 5
        bytes[8] = (byte)((bytes[8] & 0x3F) | 0x80); // RFC 4122 variant
        return new Guid(bytes, bigEndian: true).ToString("B");
    }

    /// <summary>
    /// The visible Store app profile for a distro, such as the Ubuntu app's "Ubuntu" profile.
    /// Names are compared by letters and digits only. A profile belongs to the registered distro
    /// with the longest name it matches: exactly, or as the start of the profile's name
    /// ("Ubuntu-22.04" matches "Ubuntu 22.04.5 LTS") unless the distro name ends in a letter
    /// and the profile name goes on with a digit, which means another version ("Ubuntu"
    /// mustn't match "Ubuntu 22.04 LTS"). Longest wins, so "Ubuntu Preview" belongs to
    /// Ubuntu-Preview, not Ubuntu. Of a distro's profiles, an exact match wins, then the first
    /// in settings order. Only Store profiles are matched, and their command line is replaced
    /// unless the user set one, so a wrong match normally just borrows the wrong look.
    /// </summary>
    private static TerminalProfile? DistroAppProfile(List<TerminalProfile> profiles, string distro)
    {
        var key = Normalize(distro);
        if (key.Length == 0)
        {
            return null;
        }

        var distroKeys = WslDistros.RegisteredNames().Select(Normalize).Append(key).Where(k => k.Length > 0).Distinct().ToList();
        var owned = profiles
            .Where(p => !p.Hidden && p.Kind == TerminalProfileKind.StoreApp)
            .Where(p =>
            {
                var name = Normalize(p.Name);
                return Matches(name, key) && !distroKeys.Any(k => k.Length > key.Length && Matches(name, k));
            })
            .ToList();
        return owned.FirstOrDefault(p => Normalize(p.Name) == key) ?? owned.FirstOrDefault();

        static string Normalize(string value) => new(value.Where(char.IsLetterOrDigit).Select(char.ToLowerInvariant).ToArray());

        static bool Matches(string name, string key) =>
            name.StartsWith(key, StringComparison.Ordinal)
            && (name.Length == key.Length || !(char.IsLetter(key[^1]) && char.IsDigit(name[key.Length])));
    }

    // A package family name, e.g. CanonicalGroupLimited.Ubuntu_79rhkp1fndgsc
    [GeneratedRegex(@"^[^_\s]+_[a-z0-9]{13}$", RegexOptions.IgnoreCase)]
    private static partial Regex PackageFamilyNameRegex();

    private static string? GetString(JsonElement element, string property) =>
        element.TryGetProperty(property, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;
}
